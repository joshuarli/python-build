fn path_buf_from_bytes(path: &[u8]) -> Result<PathBuf, String> {
    #[cfg(unix)]
    {
        use std::os::unix::ffi::OsStringExt;
        Ok(PathBuf::from(std::ffi::OsString::from_vec(path.to_vec())))
    }
    #[cfg(not(unix))]
    {
        let path = std::str::from_utf8(path).map_err(|error| error.to_string())?;
        Ok(PathBuf::from(path))
    }
}

