#[derive(Debug)]
struct ContextCertResolver {
    certified_keys: Vec<Arc<CertifiedKey>>,
    cipher_suites: Vec<SupportedCipherSuite>,
    server_preference: bool,
}

impl ContextCertResolver {
    fn resolve_for_suite(
        &self,
        suite: &SupportedCipherSuite,
        signature_schemes: &[SignatureScheme],
    ) -> Option<Arc<CertifiedKey>> {
        self.certified_keys
            .iter()
            .find(|certified| {
                let usable = suite.usable_for_signature_algorithm(certified.key.algorithm());
                let scheme = certified.key.choose_scheme(signature_schemes);
                usable && scheme.is_some()
            })
            .cloned()
    }
}

impl ResolvesServerCert for ContextCertResolver {
    fn resolve(&self, client_hello: ClientHello<'_>) -> Option<Arc<CertifiedKey>> {
        let offered_suites = client_hello.cipher_suites();
        let signature_schemes = client_hello.signature_schemes();
        for tls13 in [false, true] {
            if self.server_preference {
                for suite in &self.cipher_suites {
                    if (suite.version().version == rustls::ProtocolVersion::TLSv1_3) == tls13
                        && offered_suites.contains(&suite.suite())
                    {
                        if let Some(certified) = self.resolve_for_suite(suite, signature_schemes) {
                            return Some(certified);
                        }
                    }
                }
            } else {
                for offered in offered_suites {
                    if let Some(suite) = self.cipher_suites.iter().find(|suite| {
                        suite.suite() == *offered
                            && (suite.version().version == rustls::ProtocolVersion::TLSv1_3)
                                == tls13
                    }) {
                        if let Some(certified) = self.resolve_for_suite(suite, signature_schemes) {
                            return Some(certified);
                        }
                    }
                }
            }
        }
        None
    }
}

const MAX_SESSION_HOSTS: usize = 256;
const MAX_TLS13_TICKETS_PER_HOST: usize = 4;

#[derive(Default)]
struct HostSessions {
    kx_hint: Option<NamedGroup>,
    tls12: Option<Arc<SessionData>>,
    tls13: VecDeque<Arc<SessionData>>,
}

struct ContextSessionStore {
    hosts: Mutex<HashMap<String, HostSessions>>,
    context_identity: Arc<ContextIdentity>,
    require_verified_chain: bool,
}

impl fmt::Debug for ContextSessionStore {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("ContextSessionStore").finish()
    }
}

impl ContextSessionStore {
    fn new(context_identity: Arc<ContextIdentity>, require_verified_chain: bool) -> Self {
        Self {
            hosts: Mutex::new(HashMap::new()),
            context_identity,
            require_verified_chain,
        }
    }

    fn get_or_insert<'a>(
        hosts: &'a mut HashMap<String, HostSessions>,
        server_name: &ServerName<'_>,
    ) -> &'a mut HostSessions {
        let key = server_name.to_str().to_string();
        if !hosts.contains_key(&key) && hosts.len() >= MAX_SESSION_HOSTS {
            if let Some(oldest) = hosts.keys().next().cloned() {
                hosts.remove(&oldest);
            }
        }
        hosts.entry(key).or_default()
    }

    fn captured_chain() -> Option<Vec<Vec<u8>>> {
        crate::policy::capture_current_verified_chain().filter(|chain| !chain.is_empty())
    }

    fn restore_chain(chain: Option<&Vec<Vec<u8>>>) -> bool {
        chain.map_or(true, |chain| {
            crate::policy::restore_current_verified_chain(chain.to_vec())
        })
    }

    fn entry_count(&self) -> usize {
        self.hosts
            .lock().unwrap_or_else(|poisoned| poisoned.into_inner())
            .values()
            .map(|host| usize::from(host.tls12.is_some()) + host.tls13.len())
            .sum()
    }
}

impl ClientSessionStore for ContextSessionStore {
    fn set_kx_hint(&self, server_name: ServerName<'static>, group: NamedGroup) {
        let mut hosts = self.hosts.lock().unwrap_or_else(|poisoned| poisoned.into_inner());
        Self::get_or_insert(&mut hosts, &server_name).kx_hint = Some(group);
    }

    fn kx_hint(&self, server_name: &ServerName<'_>) -> Option<NamedGroup> {
        let name = server_name.to_str();
        self.hosts
            .lock().unwrap_or_else(|poisoned| poisoned.into_inner())
            .get(name.as_ref())
            .and_then(|host| host.kx_hint)
    }

    fn set_tls12_session(
        &self,
        server_name: ServerName<'static>,
        value: rustls::client::Tls12ClientSessionValue,
    ) {
        let verified_chain = Self::captured_chain();
        if self.require_verified_chain && verified_chain.is_none() {
            return;
        }
        let name = server_name.to_str().to_string();
        let session = Arc::new(SessionData::new(
            ClientSessionValue::Tls12(value),
            Arc::clone(&self.context_identity),
            name,
            verified_chain,
        ));
        let mut hosts = self.hosts.lock().unwrap_or_else(|poisoned| poisoned.into_inner());
        Self::get_or_insert(&mut hosts, &server_name).tls12 = Some(Arc::clone(&session));
        drop(hosts);
        capture_current_session(session);
    }

    fn tls12_session(
        &self,
        server_name: &ServerName<'_>,
    ) -> Option<rustls::client::Tls12ClientSessionValue> {
        let name = server_name.to_str();
        let explicit = current_session_override()?;
        let session = explicit.session_data();
        let value = explicit.tls12_clone(name.as_ref())?;
        if (self.require_verified_chain && session.verified_chain.is_none())
            || !Self::restore_chain(session.verified_chain.as_ref())
        {
            return None;
        }
        capture_current_session(session);
        Some(value)
    }

    fn remove_tls12_session(&self, server_name: &ServerName<'static>) {
        let name = server_name.to_str();
        if let Some(host) = self.hosts.lock().unwrap_or_else(|poisoned| poisoned.into_inner()).get_mut(name.as_ref()) {
            host.tls12 = None;
        }
    }

    fn insert_tls13_ticket(
        &self,
        server_name: ServerName<'static>,
        value: rustls::client::Tls13ClientSessionValue,
    ) {
        let verified_chain = Self::captured_chain();
        if self.require_verified_chain && verified_chain.is_none() {
            return;
        }
        let name = server_name.to_str().to_string();
        let session = Arc::new(SessionData::new(
            ClientSessionValue::Tls13(value),
            Arc::clone(&self.context_identity),
            name,
            verified_chain,
        ));
        let mut hosts = self.hosts.lock().unwrap_or_else(|poisoned| poisoned.into_inner());
        let tickets = &mut Self::get_or_insert(&mut hosts, &server_name).tls13;
        if tickets.len() == MAX_TLS13_TICKETS_PER_HOST {
            tickets.pop_front();
        }
        tickets.push_back(Arc::clone(&session));
        drop(hosts);
        capture_current_session(session);
    }

    fn take_tls13_ticket(
        &self,
        server_name: &ServerName<'static>,
    ) -> Option<rustls::client::Tls13ClientSessionValue> {
        let name = server_name.to_str();
        let explicit = current_session_override()?;
        let session = explicit.session_data();
        if (self.require_verified_chain && session.verified_chain.is_none())
            || !Self::restore_chain(session.verified_chain.as_ref())
        {
            return None;
        }
        let value = explicit.tls13_take(name.as_ref());
        if value.is_some() {
            capture_current_session(session);
        }
        value
    }
}

fn new_server_session_storage() -> Arc<dyn StoresServerSessions> {
    ServerSessionMemoryCache::new(256)
}

