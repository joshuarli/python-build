fn group_from_name(name: &str) -> Option<NamedGroup> {
    match name.to_ascii_lowercase().as_str() {
        "x25519" => Some(NamedGroup::X25519),
        "secp256r1" | "prime256v1" | "p-256" | "nistp256" => {
            Some(NamedGroup::secp256r1)
        }
        "secp384r1" | "p-384" | "nistp384" => Some(NamedGroup::secp384r1),
        "x25519mlkem768" => Some(NamedGroup::X25519MLKEM768),
        _ => None,
    }
}

fn group_iana_name(group: NamedGroup) -> Option<&'static str> {
    match group {
        NamedGroup::X25519 => Some("x25519"),
        NamedGroup::secp256r1 => Some("secp256r1"),
        NamedGroup::secp384r1 => Some("secp384r1"),
        NamedGroup::X25519MLKEM768 => Some("X25519MLKEM768"),
        _ => None,
    }
}

fn group_aliases(group: NamedGroup) -> &'static [&'static str] {
    match group {
        NamedGroup::secp256r1 => &["P-256", "prime256v1", "NISTP256"],
        NamedGroup::secp384r1 => &["P-384", "NISTP384"],
        NamedGroup::X25519 => &["X25519"],
        _ => &[],
    }
}

fn parse_groups(names: &str) -> Result<Vec<NamedGroup>, String> {
    let mut groups = Vec::new();
    for token in names.split(':') {
        if token.is_empty() {
            return Err("Empty TLS group name".to_string());
        }
        let (optional, name) = match token.strip_prefix('?') {
            Some(name) if !name.is_empty() => (true, name),
            Some(_) => return Err("Empty TLS group name".to_string()),
            None => (false, token),
        };
        let group = group_from_name(name);
        let available = group.filter(|group| {
            PREFERRED_KX_GROUPS.iter().any(|supported| supported.name() == *group)
        });
        match available {
            Some(group) if !groups.contains(&group) => groups.push(group),
            Some(_) => {}
            None if optional => {}
            None => return Err(format!("Unsupported TLS group: {name}")),
        }
    }
    Ok(groups)
}

