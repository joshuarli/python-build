fn supported_signature_schemes() -> Vec<SignatureScheme> {
    default_crypto_provider()
        .signature_verification_algorithms
        .supported_schemes()
}

fn parse_signature_schemes(names: &str) -> Result<Vec<SignatureScheme>, String> {
    let supported = supported_signature_schemes();
    let mut schemes = Vec::new();
    for token in names.split(':') {
        if token.is_empty() {
            return Err("Empty TLS signature algorithm name".to_string());
        }
        let (optional, name) = match token.strip_prefix('?') {
            Some(name) if !name.is_empty() => (true, name),
            Some(_) => return Err("Empty TLS signature algorithm name".to_string()),
            None => (false, token),
        };
        match signature_scheme_from_name(name).filter(|scheme| supported.contains(scheme)) {
            Some(scheme) if !schemes.contains(&scheme) => schemes.push(scheme),
            Some(_) => {}
            None if optional => {}
            None => return Err(format!("Unsupported TLS signature algorithm: {name}")),
        }
    }
    if schemes.is_empty() {
        return Err("No supported TLS signature algorithms selected".to_string());
    }
    Ok(schemes)
}

#[derive(Debug)]
struct FilteredSigningKey {
    inner: Arc<dyn SigningKey>,
    allowed: Vec<SignatureScheme>,
}

impl SigningKey for FilteredSigningKey {
    fn choose_scheme(
        &self,
        offered: &[SignatureScheme],
    ) -> Option<Box<dyn rustls::sign::Signer>> {
        self.allowed
            .iter()
            .filter(|scheme| offered.contains(scheme))
            .find_map(|scheme| self.inner.choose_scheme(&[*scheme]))
    }

    fn public_key(&self) -> Option<rustls::pki_types::SubjectPublicKeyInfoDer<'_>> {
        self.inner.public_key()
    }

    fn algorithm(&self) -> rustls::SignatureAlgorithm {
        self.inner.algorithm()
    }
}

fn certified_key(
    certs: &[CertificateDer<'static>],
    key: &PrivateKeyDer<'static>,
    provider: &rustls::crypto::CryptoProvider,
    allowed_schemes: Option<&[SignatureScheme]>,
) -> Result<CertifiedKey, String> {
    let mut certified = CertifiedKey::from_der(certs.to_vec(), key.clone_key(), provider)
        .map_err(|error| format!("Failed to load certificate key: {error}"))?;
    certified
        .keys_match()
        .map_err(|error| format!("Certificate/key mismatch: {error}"))?;
    if let Some(allowed) = allowed_schemes {
        certified.key = Arc::new(FilteredSigningKey {
            inner: Arc::clone(&certified.key),
            allowed: allowed.to_vec(),
        });
    }
    Ok(certified)
}

